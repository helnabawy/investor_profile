#!/usr/bin/env node
// Prints fresh secrets for deploy/.env: the database password, the JWT secret, and the two API
// keys signed with it (anon = public, service_role = full access, server only).
// Usage: node scripts/gen-secrets.mjs >> deploy/.env
// No Node on the server? docker run --rm -v "$PWD/scripts:/s:ro" node:22-alpine node /s/gen-secrets.mjs >> deploy/.env
import { createHmac, randomBytes } from "node:crypto";

const b64 = (v) => Buffer.from(typeof v === "string" ? v : JSON.stringify(v)).toString("base64url");
const jwtSecret = randomBytes(32).toString("hex");
const now = Math.floor(Date.now() / 1000);

function key(role) {
  // Valid for 10 years. To rotate, generate new secrets and rebuild the app image.
  const body = `${b64({ alg: "HS256", typ: "JWT" })}.${b64({ role, iss: "supabase", iat: now, exp: now + 10 * 365 * 24 * 3600 })}`;
  return `${body}.${createHmac("sha256", jwtSecret).update(body).digest("base64url")}`;
}

console.log(`
# ───────── Generated by scripts/gen-secrets.mjs — keep private ─────────
POSTGRES_PASSWORD=${randomBytes(24).toString("hex")}
JWT_SECRET=${jwtSecret}
ANON_KEY=${key("anon")}
SERVICE_ROLE_KEY=${key("service_role")}
PREVIEW_SECRET=${randomBytes(32).toString("base64url")}`);
